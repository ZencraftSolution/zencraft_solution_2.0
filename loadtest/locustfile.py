"""Load profile for Zencraft Solution.

Run this against staging. Never against production: it submits contact forms and estimator
answers, which create real records, send real email and count against real rate limits.

    pip install locust
    locust -f loadtest/locustfile.py --host https://zencraft-staging.onrender.com

See loadtest/README.md for what the numbers mean and what to watch while it runs.
"""

import random
import re

from locust import HttpUser, between, task

# The pages a real visitor opens, weighted roughly by how a small agency site is used: most
# traffic lands on the home page or a service page from search.
SERVICE_SLUGS = [
    "custom-software-development", "web-development", "mobile-application-development",
    "it-consulting", "testing-qa", "data-analytics",
]
CASE_SLUGS = [
    "mobile-banking-development-bank", "hospital-information-system",
    "omnichannel-fashion-retail", "fleet-tracking-logistics",
]
POST_SLUGS = ["fixed-price-vs-dedicated-team", "core-web-vitals-nepal-mobile", "cloud-costs-five-quick-wins"]

CSRF_RE = re.compile(r'name="csrfmiddlewaretoken" value="([^"]+)"')


class Reader(HttpUser):
    """Somebody browsing. No writes, so this profile is safe to run hard."""

    weight = 8
    wait_time = between(1, 5)

    @task(10)
    def home(self):
        self.client.get("/", name="/")

    @task(6)
    def service(self):
        slug = random.choice(SERVICE_SLUGS)  # noqa: S311  # nosec B311 - picking a page, not a secret
        self.client.get(f"/services/{slug}/", name="/services/[slug]/")

    @task(3)
    def work(self):
        self.client.get("/work/", name="/work/")
        self.client.get(f"/work/{random.choice(CASE_SLUGS)}/", name="/work/[slug]/")  # noqa: S311  # nosec B311

    @task(3)
    def pricing(self):
        self.client.get("/pricing/", name="/pricing/")

    @task(2)
    def insights(self):
        self.client.get(f"/insights/{random.choice(POST_SLUGS)}/", name="/insights/[slug]/")  # noqa: S311  # nosec B311

    @task(2)
    def careers(self):
        self.client.get("/careers/jobs/", name="/careers/jobs/")

    @task(1)
    def health(self):
        self.client.get("/healthz/", name="/healthz/")


class Enquirer(HttpUser):
    """Somebody who actually gets in touch. Writes to the database and sends email."""

    weight = 2
    wait_time = between(5, 15)

    def csrf(self, path):
        response = self.client.get(path, name=f"{path} (form)")
        match = CSRF_RE.search(response.text)
        return match.group(1) if match else ""

    @task(2)
    def contact(self):
        token = self.csrf("/contact/")
        if not token:
            return
        number = random.randint(1, 10_000_000)  # noqa: S311  # nosec B311 - a unique address, not a secret
        self.client.post(
            "/contact/",
            {
                "csrfmiddlewaretoken": token,
                "name": f"Load Test {number}",
                "email": f"loadtest+{number}@example.invalid",
                "phone": "9800000000",
                "company": "Load Test Ltd",
                "subject": "Automated load test, please ignore",
                "message": "This message was generated by loadtest/locustfile.py against staging.",
                "consent": "on",
            },
            headers={"Referer": f"{self.host}/contact/"},
            name="POST /contact/",
        )

    @task(3)
    def estimator(self):
        """The estimator's configuration endpoint, which every visitor to /estimate/ calls."""
        self.client.get("/estimate/", name="/estimate/")
        self.client.get("/estimate/config.json", name="/estimate/config.json")

    @task(1)
    def search(self):
        term = random.choice(["django", "mobile", "cloud", "audit", "healthcare"])  # noqa: S311  # nosec B311
        self.client.get(f"/search/?q={term}", name="/search/?q=")
